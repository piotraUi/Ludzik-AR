package com.ludzik.game.audio

/** Dźwięki generowane programowo przez [SoundSynth]. */
enum class Sfx {
    POP,        // postawienie postaci
    BOING,      // skok
    PLUM,       // kleks ląduje / chlapie
    SCRIBBLE,   // skrzypienie ołówka
    SQUEAK,     // gumka wymazuje
    TICK,       // tupot pająka
    ZIP,        // nitka pająka
    HEY,        // „głos” przy dymku
    SHUTTER,    // zdjęcie
    THUD,       // przedmiot uderza o podłogę/meble
}

enum class Haptic { LIGHT, MEDIUM, DOUBLE }
